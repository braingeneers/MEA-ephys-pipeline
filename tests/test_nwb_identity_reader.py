class AuditedDataset:
    def __init__(self, dataset):
        self.dataset, self.reads = dataset, []

    def __getattr__(self, name):
        return getattr(self.dataset, name)

    def __getitem__(self, key):
        result = self.dataset[key]
        self.reads.append((key, result.nbytes))
        return result


class ChannelReadTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.file = h5py.File(Path(self.directory.name) / "data.h5", "w")

    def tearDown(self):
        self.file.close()
        self.directory.cleanup()

    def dataset(self, dtype="int16"):
        values = np.arange(53 * 11).reshape(53, 11).astype(dtype)
        if np.dtype(dtype).kind in "fc":
            values[0, :4] = [np.nan, np.inf, -np.inf, -0.0]
        return self.file.create_dataset("data", data=values, chunks=(7, 1))

    def test_numeric_values_dtype_and_bits(self):
        for dtype in ["uint16", "int16", ">i2", "float32", "float64", "complex128", "bool"]:
            with self.subTest(dtype=dtype):
                dataset = self.dataset(dtype)
                view = ContiguousChannelReads(dataset, 96)
                for rows in [slice(None), slice(3, 49), slice(47, 100), slice(-9, None)]:
                    key = rows, np.array([0, 2, 3, 7, 10])
                    expected, actual = dataset[key], view[key]
                    self.assertEqual(actual.dtype, expected.dtype)
                    self.assertEqual(actual.shape, expected.shape)
                    self.assertEqual(actual.tobytes(), expected.tobytes())
                del self.file["data"]

    def test_each_source_read_is_contiguous_and_byte_bounded(self):
        audited = AuditedDataset(self.dataset("float64"))
        view = ContiguousChannelReads(audited, 24)
        key = slice(2, 52), np.array([0, 1, 2, 3, 4, 7, 9, 10])
        expected = audited.dataset[key]
        self.assertEqual(view[key].tobytes(), expected.tobytes())
        self.assertGreater(len(audited.reads), 1)
        for selection, byte_count in audited.reads:
            self.assertTrue(all(isinstance(item, slice) for item in selection))
            self.assertLessEqual(byte_count, 24)

    def test_ordinary_indexing_and_unsupported_cases_keep_h5py_behavior(self):
        dataset = self.dataset()
        view = ContiguousChannelReads(dataset, 96)
        keys = [(slice(None, None, 2), np.array([1, 3, 7])),
                (slice(3, 23), slice(1, 8)), (7, slice(None)),
                (slice(5, 5), np.array([1, 3])),
                (slice(None), np.array([], dtype="int64")),
                (slice(None), np.array([2, 1])),
                (slice(None), np.array([1, 1])),
                (slice(None), np.array([-12, 2])),
                (slice(None), np.array([0, 11])),
                (slice(None), np.array([True, False]))]
        for key in keys:
            with self.subTest(key=key):
                try:
                    expected = dataset[key]
                except Exception as error:
                    with self.assertRaisesRegex(type(error), ""):
                        view[key]
                else:
                    actual = view[key]
                    self.assertEqual(actual.dtype, expected.dtype)
                    self.assertEqual(actual.shape, expected.shape)
                    self.assertEqual(actual.tobytes(), expected.tobytes())

    def test_smallest_buffer_splits_columns_and_rows(self):
        dataset = self.dataset("float64")
        audited = AuditedDataset(dataset)
        key = slice(2, 5), np.array([0, 1, 2, 7, 8, 9, 10])
        actual = ContiguousChannelReads(audited, 8)[key]
        self.assertEqual(actual.tobytes(), dataset[key].tobytes())
        self.assertTrue(all(byte_count <= 8 for _, byte_count in audited.reads))

    def test_invalid_budget(self):
        for budget in [0, -1, True, 1.5]:
            with self.assertRaises(ValueError):
                ContiguousChannelReads(self.dataset(), budget)
            del self.file["data"]


class RecordingGraphTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.fixture = Path(os.environ["NWB_IDENTITY_FIXTURE"])
        if not cls.fixture.is_file():
            raise ValueError("Generate and validate NWB_IDENTITY_FIXTURE in the native image first")

    def raw(self):
        return NwbRecordingExtractor(self.fixture, electrical_series_path="acquisition/ElectricalSeries",
                                     load_time_vector=False, cache=False)

    def graph(self):
        raw = self.raw()
        highpass = preprocessing.highpass_filter(raw.select_segments([0]), freq_min=300,
                                                 margin_ms=5, dtype="int16")
        selected = highpass.select_channels([f"ch{i}" for i in range(16) if i not in (3, 11)])
        referenced = preprocessing.common_reference(selected, reference="global", operator="median")
        return raw, referenced.select_channels([f"ch{i}" for i in [15, 0, 2, 4, 8, 12]])

    def test_real_parent_chain_values_and_serialization_are_exact(self):
        raw, recording = self.graph()
        segment = raw._recording_segments[0]
        original = segment.electrical_series_data
        before = portable.encoded(recording.to_dict(recursive=True))
        expected = [recording.get_traces(start_frame=37, end_frame=20049,
                                        channel_ids=["ch8", "ch15", "ch0"], return_scaled=scaled)
                    for scaled in (False, True)]
        with bounded_nwb_reads(recording, 1024):
            self.assertIsInstance(segment.electrical_series_data, ContiguousChannelReads)
            for scaled, values in zip((False, True), expected):
                actual = recording.get_traces(start_frame=37, end_frame=20049,
                                              channel_ids=["ch8", "ch15", "ch0"], return_scaled=scaled)
                self.assertEqual(actual.dtype, values.dtype)
                self.assertEqual(actual.tobytes(), values.tobytes())
            self.assertEqual(before, portable.encoded(recording.to_dict(recursive=True)))
        self.assertIs(segment.electrical_series_data, original)
        self.assertEqual(before, portable.encoded(recording.to_dict(recursive=True)))

    def test_complete_fingerprint_matches_original_algorithm(self):
        _, recording = self.graph()
        graph = recording.to_dict(recursive=True)
        original = portable._recording_identity_values(si.load(graph))
        optimized = portable.recording_identity(si.load(graph))
        self.assertEqual(portable.encoded(original), portable.encoded(optimized))
        self.assertEqual(original["read_policy"]["frames_per_block"], 65536)
        self.assertEqual(original["segments"][0]["frames"], 131251)

    def test_multiple_parent_recordings_and_exception_restoration(self):
        first, second = self.raw(), self.raw()
        combined = si.append_recordings([first, second])
        segments = [first._recording_segments[0], second._recording_segments[0]]
        originals = [segment.electrical_series_data for segment in segments]
        with self.assertRaisesRegex(RuntimeError, "deliberate"):
            with bounded_nwb_reads(combined):
                self.assertTrue(all(isinstance(s.electrical_series_data, ContiguousChannelReads)
                                    for s in segments))
                raise RuntimeError("deliberate")
        self.assertTrue(all(s.electrical_series_data is d for s, d in zip(segments, originals)))

    def test_non_nwb_recording_retains_identity(self):
        recording = si.NumpyRecording(np.arange(400).reshape(100, 4).astype("int16"), 10000)
        recording.set_channel_gains(0.195)
        recording.set_channel_offsets(-1.0)
        expected = portable._recording_identity_values(recording)
        self.assertEqual(portable.encoded(expected), portable.encoded(portable.recording_identity(recording)))


if __name__ == "__main__":
    unittest.main()
